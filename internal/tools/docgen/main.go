// Command docgen writes the reference pages the documentation draws
// from the code: the entity types and the built-in transforms. Run it
// with `task docs-gen` after adding a type or a transform.
package main

import (
	"cmp"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/yousysadmin/gosint/internal/core/transform"
	"github.com/yousysadmin/gosint/internal/core/types"
	"github.com/yousysadmin/gosint/internal/transforms"
)

const generated = "<!-- Generated by internal/tools/docgen (task docs-gen). Edit the code, not this file. -->"

func main() {
	out := flag.String("out", "docs/content/reference", "directory the pages are written to")
	flag.Parse()

	pages := map[string]string{
		"entity-types.md": entityTypes(types.Builtin().All()),
		"transforms.md":   transformList(transforms.All()),
	}

	for name, body := range pages {
		path := filepath.Join(*out, name)
		if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
			fmt.Fprintln(os.Stderr, "docgen:", err)
			os.Exit(1)
		}

		fmt.Println("wrote", path)
	}
}

// cell makes text safe inside a table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")

	return strings.Join(strings.Fields(s), " ")
}

func categoryTitle(key string) string {
	for _, c := range types.Categories {
		if c.Key == key {
			return c.Title
		}
	}

	return key
}

func entityTypes(all []*types.Type) string {
	var b strings.Builder

	b.WriteString(`---
title: Entity types
description: "Every built-in entity type, its fields and how a value is recognized."
weight: 30
---

` + generated + `

An entity's identity in a sketch is its type and its **primary** field:
adding the same value again updates the entity instead of making a
second one. A type marked *detected* is recognized in pasted text.
Fields not listed here are kept too, as custom fields. An administrator
can add types of their own, see [custom types](/extending/custom-types/).

`)

	current := ""
	for _, t := range all {
		if t.Category != current {
			current = t.Category
			fmt.Fprintf(&b, "## %s\n\n", categoryTitle(current))
		}

		fmt.Fprintf(&b, "### %s\n\n`%s`", t.Title, t.Name)
		if t.Detect != nil {
			b.WriteString(", detected")
		}

		b.WriteString("\n\n")
		if t.Description != "" {
			fmt.Fprintf(&b, "%s\n\n", strings.TrimSpace(t.Description))
		}

		if len(t.Fields) == 0 {
			continue
		}

		b.WriteString("| Field | Kind | Notes |\n| --- | --- | --- |\n")
		for _, f := range t.Fields {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", f.Name, kindOf(f), cell(fieldNotes(f)))
		}

		b.WriteString("\n")
	}

	return b.String()
}

func kindOf(f types.Field) string {
	switch f.Kind {
	case types.KindList:
		if f.Elem == types.KindRef {
			return "list of " + f.Ref
		}

		return "list of " + string(f.Elem)
	case types.KindRef:
		return f.Ref
	default:
		return string(f.Kind)
	}
}

func fieldNotes(f types.Field) string {
	var notes []string

	if f.Primary {
		notes = append(notes, "**primary**")
	}

	if f.Required {
		notes = append(notes, "required")
	}

	if f.Secret {
		notes = append(notes, "secret, masked until shown")
	}

	if f.VaultKey {
		notes = append(notes, "names a secret")
	}

	if f.Description != "" {
		notes = append(notes, strings.TrimSuffix(strings.TrimSpace(f.Description), "."))
	}

	if len(f.Options) > 0 {
		notes = append(notes, "one of "+strings.Join(f.Options, ", "))
	}

	if f.Default != nil {
		notes = append(notes, fmt.Sprintf("default %v", f.Default))
	}

	if f.Min != nil && f.Max != nil {
		notes = append(notes, fmt.Sprintf("from %v to %v", *f.Min, *f.Max))
	}

	return strings.Join(notes, ", ")
}

func transformList(all []transform.Transform) string {
	metas := make([]transform.Meta, 0, len(all))
	for _, t := range all {
		metas = append(metas, t.Meta())
	}

	slices.SortFunc(metas, func(a, b transform.Meta) int {
		return cmp.Or(cmp.Compare(a.Category, b.Category), cmp.Compare(a.Name, b.Name))
	})

	var b strings.Builder

	fmt.Fprintf(&b, `---
title: Transforms
description: "The %d built-in transforms: what each takes, what it finds and the secrets it asks for."
weight: 40
---

%s

A transform takes entities of its **input** type and writes what it
finds, mostly entities of its **output** type linked to the input. How
to run one is in [transforms](/guide/transforms/). A secret is the name
of a key you keep on the [Secrets](/guide/secrets/) page, never the
value itself.

`, len(metas), generated)

	b.WriteString(secretsTable(metas))

	current := ""
	for _, m := range metas {
		if m.Category != current {
			current = m.Category
			fmt.Fprintf(&b, "## %s\n\n", current)
		}

		fmt.Fprintf(&b, "### %s\n\n", m.Name)
		if m.Description != "" {
			fmt.Fprintf(&b, "%s\n\n", strings.TrimSpace(m.Description))
		}

		fmt.Fprintf(&b, "Takes %s, finds %s.\n\n", typeName(m.Input, "any entity"), typeName(m.Output, "what the fields name"))

		if len(m.Params) == 0 {
			continue
		}

		b.WriteString("| Parameter | Kind | Default | Description |\n| --- | --- | --- | --- |\n")
		for _, p := range m.Params {
			name := "`" + p.Name + "`"
			if p.Required {
				name += " (required)"
			}

			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", name, paramKind(p), cell(defaultOf(p)), cell(paramNotes(p)))
		}

		b.WriteString("\n")
	}

	return b.String()
}

func typeName(name, empty string) string {
	if name == "" {
		return empty
	}

	return "`" + name + "`"
}

func paramKind(p transform.Param) string {
	if p.Type == transform.ParamSecret {
		return "secret"
	}

	return string(p.Type)
}

func defaultOf(p transform.Param) string {
	if p.Default == "" {
		return ""
	}

	return "`" + p.Default + "`"
}

func paramNotes(p transform.Param) string {
	notes := strings.TrimSpace(p.Description)
	if len(p.Options) == 0 {
		return notes
	}

	values := make([]string, 0, len(p.Options))
	for _, o := range p.Options {
		values = append(values, "`"+o.Value+"`")
	}

	return strings.TrimSpace(notes + " One of " + strings.Join(values, ", ") + ".")
}

// secretsTable lists every secret name with the transforms asking for
// it, so the Secrets page can be filled in one go.
func secretsTable(metas []transform.Meta) string {
	type use struct {
		required, optional []string
	}

	uses := map[string]*use{}

	for _, m := range metas {
		for _, p := range m.Params {
			if p.Type != transform.ParamSecret {
				continue
			}

			u := uses[p.Name]
			if u == nil {
				u = &use{}
				uses[p.Name] = u
			}

			if p.Required {
				u.required = append(u.required, "`"+m.Name+"`")
			} else {
				u.optional = append(u.optional, "`"+m.Name+"`")
			}
		}
	}

	names := make([]string, 0, len(uses))
	for n := range uses {
		names = append(names, n)
	}

	slices.Sort(names)

	var b strings.Builder

	b.WriteString("## Secrets\n\n| Secret | Required by | Optional for |\n| --- | --- | --- |\n")
	for _, n := range names {
		u := uses[n]
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", n, strings.Join(u.required, ", "), strings.Join(u.optional, ", "))
	}

	b.WriteString("\n")

	return b.String()
}
